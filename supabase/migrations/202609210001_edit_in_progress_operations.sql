create or replace function public.get_operation_change_history(p_operation_id bigint)
returns table(
  history_id bigint,
  change_group_id uuid,
  change_type text,
  description text,
  old_value jsonb,
  new_value jsonb,
  changed_by uuid,
  changed_by_name text,
  changed_at timestamp without time zone
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.has_role('DIRECTOR') then
    raise exception 'No tienes permisos para consultar el historial de cambios';
  end if;

  if not exists (
    select 1
    from public.operation o
    where o.id = p_operation_id
      and public.has_client_access(o.client_id)
  ) then
    raise exception 'La operacion no existe o no tienes acceso';
  end if;

  return query
  select
    h.id,
    h.change_group_id,
    h.change_type,
    h.description,
    h.old_value,
    h.new_value,
    h.changed_by,
    h.changed_by_name,
    h.changed_at
  from public.operation_change_history h
  where h.operation_id = p_operation_id
  order by h.changed_at desc, h.id desc;
end;
$$;

