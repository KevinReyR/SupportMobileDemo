create or replace function public.calculate_direct_payroll(p_period_start date)
returns table (
  period_id bigint,
  contractor_id bigint,
  contractor_name text,
  eligible_days numeric,
  paid_days numeric,
  base_salary_amount numeric,
  status text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_start date := date_trunc('month', p_period_start::timestamp)::date;
  normalized_end date := (date_trunc('month', p_period_start::timestamp) + interval '1 month - 1 day')::date;
  actor uuid := auth.uid();
begin
  if actor is null or not public.is_active_user() or not public.has_role('ADMIN') then
    raise exception 'No autorizado';
  end if;
  if p_period_start <> normalized_start then
    raise exception 'El periodo debe iniciar el primer dia del mes';
  end if;
  if normalized_start > date_trunc('month', public.colombia_today()::timestamp)::date then
    raise exception 'No se puede calcular un periodo futuro';
  end if;

  insert into public.contractor_payroll_periods(
    contractor_id, contractor_contract_id, payroll_rule_id,
    period_start, period_end, monthly_salary_snapshot,
    eligible_days, paid_days, base_salary_amount,
    status, calculated_at, created_by, updated_by
  )
  select
    cc.contractor_id,
    cc.id,
    rule.id,
    normalized_start,
    normalized_end,
    rule.monthly_salary,
    public.payroll_30_360_days(
      greatest(cc.start_date, normalized_start),
      least(coalesce(cc.end_date, normalized_end), normalized_end)
    ),
    public.payroll_30_360_days(
      greatest(cc.start_date, normalized_start),
      least(coalesce(cc.end_date, normalized_end), normalized_end)
    ),
    round(
      rule.monthly_salary
      * public.payroll_30_360_days(
          greatest(cc.start_date, normalized_start),
          least(coalesce(cc.end_date, normalized_end), normalized_end)
        )
      / 30.0,
      2
    ),
    'DRAFT',
    public.colombia_now(),
    actor,
    actor
  from public.contractor_contract cc
  join public.contract_type ct on ct.id = cc.contract_type and upper(ct.name) = 'DIRECTO'
  join public.contract_type_payroll_rules rule
    on rule.contract_type_id = ct.id
   and rule.payroll_mode = 'MONTHLY_FIXED'
   and rule.status = 'ACTIVO'
   and rule.valid_from <= normalized_start
   and (rule.valid_to is null or rule.valid_to >= normalized_end)
  where cc.start_date <= normalized_end
    and (cc.end_date is null or cc.end_date >= normalized_start)
  on conflict (contractor_contract_id, period_start, period_end) do update
  set payroll_rule_id = excluded.payroll_rule_id,
      monthly_salary_snapshot = excluded.monthly_salary_snapshot,
      eligible_days = excluded.eligible_days,
      paid_days = least(contractor_payroll_periods.paid_days, excluded.eligible_days),
      base_salary_amount = round(
        excluded.monthly_salary_snapshot
        * least(contractor_payroll_periods.paid_days, excluded.eligible_days)
        / 30.0,
        2
      ),
      calculated_at = public.colombia_now(),
      updated_by = actor
  where contractor_payroll_periods.status = 'DRAFT';

  if exists (
    select 1
    from public.contractor_contract cc
    join public.contract_type ct on ct.id = cc.contract_type and upper(ct.name) = 'DIRECTO'
    where cc.start_date <= normalized_end
      and (cc.end_date is null or cc.end_date >= normalized_start)
      and not exists (
        select 1 from public.contract_type_payroll_rules rule
        where rule.contract_type_id = ct.id
          and rule.payroll_mode = 'MONTHLY_FIXED'
          and rule.status = 'ACTIVO'
          and rule.valid_from <= normalized_start
          and (rule.valid_to is null or rule.valid_to >= normalized_end)
      )
  ) then
    raise exception 'No existe una regla salarial DIRECTO vigente para el periodo';
  end if;

  return query
  select pp.id, pp.contractor_id,
    trim(concat_ws(' ', c.name, c.last_name)),
    pp.eligible_days, pp.paid_days, pp.base_salary_amount, pp.status
  from public.contractor_payroll_periods pp
  join public.contractor c on c.id = pp.contractor_id
  where pp.period_start = normalized_start
  order by c.name, c.last_name;
end;
$$;

create or replace function public.update_direct_payroll_draft(
  p_period_id bigint,
  p_paid_days numeric
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  actor uuid := auth.uid();
begin
  if actor is null or not public.is_active_user() or not public.has_role('ADMIN') then
    raise exception 'No autorizado';
  end if;

  update public.contractor_payroll_periods
  set paid_days = p_paid_days,
      base_salary_amount = round(monthly_salary_snapshot * p_paid_days / 30.0, 2),
      calculated_at = public.colombia_now(),
      updated_by = actor
