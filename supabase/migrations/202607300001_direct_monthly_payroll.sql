-- Monthly fixed payroll for DIRECTO contracts.
-- This migration installs the model and RPCs but does not backfill or close
-- production payroll periods automatically.

create table if not exists public.contract_type_payroll_rules (
  id bigint generated by default as identity primary key,
  contract_type_id bigint not null references public.contract_type(id) on update cascade on delete restrict,
  payroll_mode text not null,
  monthly_salary numeric(16,2),
  valid_from date not null,
  valid_to date,
  status text not null default 'ACTIVO',
  created_by uuid references auth.users(id) on update cascade on delete set null,
  updated_by uuid references auth.users(id) on update cascade on delete set null,
  created_at timestamp without time zone not null default public.colombia_now(),
  updated_at timestamp without time zone not null default public.colombia_now(),
  constraint contract_type_payroll_rules_mode_check check (payroll_mode in ('PER_SHIFT', 'MONTHLY_FIXED')),
  constraint contract_type_payroll_rules_status_check check (status in ('ACTIVO', 'INACTIVO')),
  constraint contract_type_payroll_rules_salary_check check (
    (payroll_mode = 'PER_SHIFT' and monthly_salary is null)
    or (payroll_mode = 'MONTHLY_FIXED' and monthly_salary > 0)
  ),
  constraint contract_type_payroll_rules_range_check check (valid_to is null or valid_to >= valid_from),
  constraint contract_type_payroll_rules_month_boundary_check check (
    extract(day from valid_from) = 1
    and (valid_to is null or valid_to = (date_trunc('month', valid_to::timestamp) + interval '1 month - 1 day')::date)
  )
);

create index if not exists idx_contract_type_payroll_rules_type
  on public.contract_type_payroll_rules(contract_type_id, valid_from, valid_to);

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'ex_contract_type_payroll_rules_no_active_overlap'
      and conrelid = 'public.contract_type_payroll_rules'::regclass
  ) then
    alter table public.contract_type_payroll_rules
      add constraint ex_contract_type_payroll_rules_no_active_overlap
      exclude using gist (
        contract_type_id with =,
        daterange(valid_from, coalesce(valid_to, 'infinity'::date), '[]') with &&
      )
      where (status = 'ACTIVO');
  end if;
end;
$$;

