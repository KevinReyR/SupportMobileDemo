create or replace function public.payroll_30_360_day(p_date date)
returns integer
language sql
immutable
strict
set search_path = public
as $$
  select case
    when p_date = (date_trunc('month', p_date::timestamp) + interval '1 month - 1 day')::date then 30
    else least(extract(day from p_date)::integer, 30)
  end;
$$;

create or replace function public.payroll_30_360_days(
  p_start date,
  p_end date
)
returns integer
language plpgsql
immutable
strict
set search_path = public
as $$
declare
  cursor_month date;
  month_end date;
  slice_start date;
  slice_end date;
  result integer := 0;
begin
  if p_start > p_end then
    return 0;
  end if;

  cursor_month := date_trunc('month', p_start::timestamp)::date;
  while cursor_month <= p_end loop
    month_end := (cursor_month + interval '1 month - 1 day')::date;
    slice_start := greatest(p_start, cursor_month);
    slice_end := least(p_end, month_end);
    result := result
      + public.payroll_30_360_day(slice_end)
      - public.payroll_30_360_day(slice_start)
      + 1;
    cursor_month := (cursor_month + interval '1 month')::date;
  end loop;
  return result;
end;
$$;

