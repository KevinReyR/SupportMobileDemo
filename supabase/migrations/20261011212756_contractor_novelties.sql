-- Contractor-specific novelties are private internal records, separate from operations and payroll.
create table public.contractor_novelties (
  id bigint generated by default as identity primary key,
  contractor_id bigint not null references public.contractor(id),
  start_date date not null,
  end_date date,
  type_code text not null,
  subtype_code text,
  is_justified boolean not null,
  description text not null,
  created_by uuid not null default auth.uid() references auth.users(id),
  updated_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint contractor_novelties_date_order_check
    check (end_date is null or end_date >= start_date),
  constraint contractor_novelties_description_check
    check (btrim(description) <> ''),
  constraint contractor_novelties_type_subtype_check
    check (
      (type_code = 'VACACIONES' and subtype_code is null)
      or (subtype_code is not null and (
        (type_code = 'INCAPACIDAD' and subtype_code in ('MEDICA', 'ACCIDENTE_TRABAJO'))
        or (type_code = 'PERMISO' and subtype_code in ('REMUNERADO', 'NO_REMUNERADO'))
        or (type_code = 'LICENCIA' and subtype_code in ('MATERNIDAD', 'PATERNIDAD', 'LUTO', 'OTRA'))
        or (type_code = 'ASISTENCIA' and subtype_code in ('TARDANZA', 'AUSENCIA', 'ABANDONO'))
      ))
    )
);

create index contractor_novelties_contractor_start_idx
  on public.contractor_novelties(contractor_id, start_date desc, created_at desc);
create index contractor_novelties_created_by_idx
  on public.contractor_novelties(created_by);
create index contractor_novelties_updated_by_idx
  on public.contractor_novelties(updated_by)
  where updated_by is not null;

create function public.set_contractor_novelty_updated_audit()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  new.updated_by = auth.uid();
  return new;
end;
$$;

create trigger contractor_novelties_updated_audit
before update on public.contractor_novelties
for each row execute function public.set_contractor_novelty_updated_audit();

alter table public.contractor_novelties enable row level security;

create policy contractor_novelties_internal_read
on public.contractor_novelties for select to authenticated
using ((select public.has_role('COORDINATOR')) or (select public.has_role('DIRECTOR')));

create policy contractor_novelties_internal_insert
on public.contractor_novelties for insert to authenticated
with check (
  ((select public.has_role('COORDINATOR')) or (select public.has_role('DIRECTOR')))
  and created_by = (select auth.uid())
);

create policy contractor_novelties_internal_update
on public.contractor_novelties for update to authenticated
using ((select public.has_role('COORDINATOR')) or (select public.has_role('DIRECTOR')))
with check ((select public.has_role('COORDINATOR')) or (select public.has_role('DIRECTOR')));

-- Column-level grants preserve contractor and creation audit fields on edits.
revoke all on public.contractor_novelties from public, anon, authenticated;
grant select on public.contractor_novelties to authenticated;
grant insert (contractor_id, start_date, end_date, type_code, subtype_code, is_justified, description)
  on public.contractor_novelties to authenticated;
grant update (start_date, end_date, type_code, subtype_code, is_justified, description)
  on public.contractor_novelties to authenticated;
