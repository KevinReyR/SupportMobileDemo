-- Global, versioned extra-hour costs for DIRECTO contracts.
create table public.direct_extra_hour_rates (
  id bigint generated by default as identity primary key,
  rate_type text not null check (rate_type in ('DIURNA', 'NOCTURNA', 'FESTIVA')),
  hourly_amount numeric(12, 2) not null check (hourly_amount > 0),
  valid_from date not null,
  valid_to date,
  created_at timestamp without time zone not null default public.colombia_now(),
  updated_at timestamp without time zone not null default public.colombia_now(),
  constraint direct_extra_hour_rates_valid_range check (valid_to is null or valid_to >= valid_from),
  constraint direct_extra_hour_rates_no_overlap exclude using gist (
    rate_type with =,
    daterange(valid_from, coalesce(valid_to, 'infinity'::date), '[]') with &&
  )
);

create index direct_extra_hour_rates_lookup
  on public.direct_extra_hour_rates(rate_type, valid_from desc);

create trigger direct_extra_hour_rates_set_updated_at
before update on public.direct_extra_hour_rates
for each row execute function public.set_updated_at();

alter table public.direct_extra_hour_rates enable row level security;
create policy direct_extra_hour_rates_admin_select on public.direct_extra_hour_rates
for select to authenticated using (public.has_role('ADMIN'));
create policy direct_extra_hour_rates_admin_insert on public.direct_extra_hour_rates
for insert to authenticated with check (public.has_role('ADMIN'));
create policy direct_extra_hour_rates_admin_update on public.direct_extra_hour_rates
for update to authenticated
using (public.has_role('ADMIN')) with check (public.has_role('ADMIN'));
grant select, insert, update on public.direct_extra_hour_rates to authenticated;
grant usage, select on sequence public.direct_extra_hour_rates_id_seq to authenticated;

