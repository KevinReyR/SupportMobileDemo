create or replace function private.direct_extra_hour_kind(p_shift_name text)
returns text
language sql immutable strict set search_path = ''
as $$
  select case regexp_replace(upper(btrim(p_shift_name)), '\s+', ' ', 'g')
    when 'DIURNO' then 'DIURNA'
    when 'MEDIO DIURNO' then 'DIURNA'
    when 'NOCTURNO' then 'NOCTURNA'
    when 'MEDIO NOCTURNO' then 'NOCTURNA'
    when 'FESTIVO' then 'FESTIVA'
  end;
$$;

create or replace function private.current_direct_extra_hour_rate(
  p_shift_id bigint, p_operation_date date
)
returns numeric
language plpgsql volatile security definer set search_path = ''
as $$
declare
  selected_shift_name text;
  selected_kind text;
  selected_amount numeric;
begin
  select s.name into selected_shift_name from public.shift s where s.id = p_shift_id;
  selected_kind := private.direct_extra_hour_kind(selected_shift_name);
  if selected_kind is null then
    raise exception 'No se puede clasificar la hora extra del turno %',
      coalesce(selected_shift_name, 'sin nombre');
  end if;

  select r.hourly_amount into selected_amount
  from public.direct_extra_hour_rates r
  where r.rate_type = selected_kind
    and r.valid_from <= p_operation_date
    and (r.valid_to is null or r.valid_to >= p_operation_date)
  limit 1
  for share;
  if selected_amount is null then
    raise exception 'No hay tarifa de hora extra DIRECTO % vigente para %',
      selected_kind, p_operation_date;
  end if;
  return selected_amount;
end;
$$;

revoke all on function private.direct_extra_hour_kind(text) from public, anon, authenticated;
revoke all on function private.current_direct_extra_hour_rate(bigint, date) from public, anon, authenticated;

-- Do not rewrite a price or validity that has already priced closed work.
create or replace function private.protect_used_direct_extra_hour_rate()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  latest_used_date date;
begin
  select max(o.operation_date) into latest_used_date
  from public.shift_costs sc
  join public.cost_concepts concept on concept.id = sc.cost_concept_id
    and concept.code = 'COSTO_HORA_EXTRA'
  join public.contract_type ct on ct.id = sc.contract_type_id
    and upper(ct.name) = 'DIRECTO'
  join public.operation o on o.id = sc.operation_id
  join public.shift s on s.id = o.shift_id
  where private.direct_extra_hour_kind(s.name) = old.rate_type
    and o.operation_date between old.valid_from and coalesce(old.valid_to, 'infinity'::date);

  if tg_op = 'DELETE' then
    if latest_used_date is not null then
      raise exception 'La tarifa DIRECTO ya se usó y no se puede eliminar';
    end if;
    return old;
  end if;

  if latest_used_date is not null and (
    new.rate_type is distinct from old.rate_type
    or new.hourly_amount is distinct from old.hourly_amount
    or new.valid_from is distinct from old.valid_from
    or (new.valid_to is not null and new.valid_to < latest_used_date)
  ) then
    raise exception 'La tarifa DIRECTO ya se usó; crea una nueva vigencia sin cambiar el valor histórico';
  end if;
  return new;
end;
$$;

create trigger direct_extra_hour_rates_protect_used
before update or delete on public.direct_extra_hour_rates
for each row execute function private.protect_used_direct_extra_hour_rate();

revoke all on function private.protect_used_direct_extra_hour_rate() from public, anon, authenticated;

-- The existing finalize/edit RPCs write assignment costs. This trigger replaces only
-- DIRECTO extra-hour cost, leaving sale rates and other contracts untouched.
create or replace function private.price_direct_extra_hours_on_assignment()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare
  target_date date;
  target_shift_id bigint;
  target_contract_type text;
  selected_amount numeric;
begin
  if coalesce(new.extra_hours, 0) <= 0 then return new; end if;

  select o.operation_date, o.shift_id into target_date, target_shift_id
  from public.operation o where o.id = new.operation_id;
  if target_date is null or target_shift_id is null then return new; end if;

  select ct.name into target_contract_type
  from public.contractor_contract contract
  join public.contract_type ct on ct.id = contract.contract_type
  where contract.contractor_id = new.contractor_id
    and contract.start_date <= target_date
    and (contract.end_date is null or contract.end_date >= target_date)
  order by contract.start_date desc nulls last, contract.id desc
  limit 1;

  if upper(coalesce(target_contract_type, '')) <> 'DIRECTO' then return new; end if;
  selected_amount := private.current_direct_extra_hour_rate(target_shift_id, target_date);
  new.unit_extra_hour_cost_price := selected_amount;
  new.total_cost := coalesce(new.worked_quantity, 0) * coalesce(new.unit_cost_price, 0)
    + new.extra_hours * selected_amount;
  return new;
end;
$$;

create trigger operation_assignment_price_direct_extra_hours
before insert or update of extra_hours, worked_quantity, contractor_id, operation_id, unit_cost_price
on public.operation_assignment
for each row execute function private.price_direct_extra_hours_on_assignment();

revoke all on function private.price_direct_extra_hours_on_assignment() from public, anon, authenticated;

-- Reprice materialized costs at approval and, once, for historical closed work.
create or replace function private.refresh_direct_extra_hour_costs(p_operation_id bigint)
returns void language plpgsql security definer set search_path = ''
as $$
declare
  target_assignment record;
  selected_amount numeric;
begin
  for target_assignment in
    select oa.id, oa.extra_hours, oa.unit_extra_hour_cost_price,
      o.operation_date, o.shift_id
    from public.operation_assignment oa
    join public.operation o on o.id = oa.operation_id and o.status = 'CERRADO'
    join lateral (
      select ct.name
      from public.contractor_contract contract
      join public.contract_type ct on ct.id = contract.contract_type
      where contract.contractor_id = oa.contractor_id
        and contract.start_date <= o.operation_date
        and (contract.end_date is null or contract.end_date >= o.operation_date)
      order by contract.start_date desc nulls last, contract.id desc
      limit 1
    ) current_contract on true
    where oa.operation_id = p_operation_id
      and oa.deleted_at is null and oa.extra_hours > 0
      and upper(current_contract.name) = 'DIRECTO'
  loop
    selected_amount := private.current_direct_extra_hour_rate(
      target_assignment.shift_id, target_assignment.operation_date
    );
    update public.operation_assignment oa
    set unit_extra_hour_cost_price = selected_amount,
        total_cost = coalesce(oa.total_cost, 0)
          + target_assignment.extra_hours *
            (selected_amount - coalesce(target_assignment.unit_extra_hour_cost_price, 0)),
        updated_at = public.colombia_now()
    where oa.id = target_assignment.id;

    update public.shift_costs sc
    set rule_value = selected_amount,
        base_cost_amount = sc.extra_hours * selected_amount,
        total_cost = sc.extra_hours * selected_amount,
        notes = 'Costo hora extra DIRECTO según tarifa vigente',
        updated_at = public.colombia_now()
    from public.cost_concepts concept
    where sc.operation_assignment_id = target_assignment.id
      and concept.id = sc.cost_concept_id and concept.code = 'COSTO_HORA_EXTRA';

    update public.shift_costs sc
    set base_cost_amount = oa.total_cost,
        total_cost = oa.total_cost * sc.rule_value / 100,
        updated_at = public.colombia_now()
    from public.operation_assignment oa
    where sc.operation_assignment_id = target_assignment.id
      and oa.id = target_assignment.id
      and sc.calculation_type = 'PERCENTAGE_OF_BASE_COST';
  end loop;
end;
$$;

revoke all on function private.refresh_direct_extra_hour_costs(bigint) from public, anon, authenticated;

create or replace function public.review_operation(
  p_operation_id bigint, p_decision varchar, p_observations text default null
)
returns void language plpgsql security definer set search_path = public
as $$
begin
  perform public.review_operation_without_direct_shift(p_operation_id, p_decision, p_observations);
  if p_decision = 'CERRADO' then
    perform private.refresh_direct_extra_hour_costs(p_operation_id);
    perform public.materialize_direct_shift_costs(p_operation_id, auth.uid());
  end if;
end;
$$;

revoke execute on function public.review_operation(bigint, varchar, text) from public, anon;
grant execute on function public.review_operation(bigint, varchar, text) to authenticated;

-- Keep a row-level recovery snapshot of every DIRECTO extra-hour cost repriced below.
create table private.direct_extra_hour_cost_backup (
  shift_cost_id bigint primary key,
  operation_assignment_id bigint not null,
  operation_date date not null,
  old_rule_value numeric,
  old_base_cost_amount numeric,
  old_shift_total_cost numeric,
  old_unit_extra_hour_cost_price numeric,
  old_assignment_total_cost numeric,
  captured_at timestamp without time zone not null default public.colombia_now()
);
revoke all on private.direct_extra_hour_cost_backup from public, anon, authenticated;

insert into private.direct_extra_hour_cost_backup (
  shift_cost_id, operation_assignment_id, operation_date,
  old_rule_value, old_base_cost_amount, old_shift_total_cost,
  old_unit_extra_hour_cost_price, old_assignment_total_cost
)
select sc.id, oa.id, o.operation_date,
  sc.rule_value, sc.base_cost_amount, sc.total_cost,
  oa.unit_extra_hour_cost_price, oa.total_cost
from public.shift_costs sc
join public.cost_concepts concept on concept.id = sc.cost_concept_id
  and concept.code = 'COSTO_HORA_EXTRA'
join public.contract_type ct on ct.id = sc.contract_type_id
  and upper(ct.name) = 'DIRECTO'
join public.operation_assignment oa on oa.id = sc.operation_assignment_id
join public.operation o on o.id = sc.operation_id and o.status = 'CERRADO';

do $$
declare
  target_operation record;
begin
  for target_operation in
    select distinct sc.operation_id
    from public.shift_costs sc
    join public.cost_concepts concept on concept.id = sc.cost_concept_id
      and concept.code = 'COSTO_HORA_EXTRA'
    join public.contract_type ct on ct.id = sc.contract_type_id
      and upper(ct.name) = 'DIRECTO'
    order by sc.operation_id
  loop
    perform private.refresh_direct_extra_hour_costs(target_operation.operation_id);
  end loop;
end;
$$;

