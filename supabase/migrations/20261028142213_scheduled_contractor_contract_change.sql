create extension if not exists pg_cron;

create table public.contractor_contract_transitions (
  id bigint generated by default as identity primary key,
  contractor_id bigint not null references public.contractor(id),
  old_contract_id bigint not null references public.contractor_contract(id),
  new_contract_id bigint not null unique references public.contractor_contract(id),
  old_end_date date not null,
  new_start_date date not null,
  status text not null check (status in ('SCHEDULED', 'COMPLETED', 'CANCELLED')),
  created_by uuid references auth.users(id) on delete set null,
  created_by_name text not null,
  created_at timestamp without time zone not null default public.colombia_now(),
  completed_at timestamp without time zone,
  cancelled_at timestamp without time zone,
  cancelled_by uuid references auth.users(id) on delete set null,
  check (new_start_date > old_end_date)
);

create unique index contractor_one_scheduled_transition
  on public.contractor_contract_transitions(contractor_id)
  where status = 'SCHEDULED';

alter table public.contractor_contract_transitions enable row level security;
revoke all on public.contractor_contract_transitions from public, anon, authenticated;

create or replace function public.contractor_current_status(p_contractor_id bigint)
returns text
language sql stable security definer
set search_path = public, pg_temp
as $$
  select coalesce(
    (select 'ACTIVO'::text
     from public.contractor_contract cc
     join public.contract_status cs on cs.id = cc.status_id
     where cc.contractor_id = p_contractor_id
       and cc.start_date <= public.colombia_today()
       and (cc.end_date is null or cc.end_date >= public.colombia_today())
       and (upper(cs.name) = 'ACTIVO'
         or (upper(cs.name) = 'PROGRAMADO' and exists (
           select 1 from public.contractor_contract_transitions t
           where t.new_contract_id = cc.id and t.status = 'SCHEDULED'
         )))
     order by cc.start_date desc, cc.id desc limit 1),
    (select 'PENDIENTE'::text
     from public.contractor_contract cc
     join public.contract_status cs on cs.id = cc.status_id
     where cc.contractor_id = p_contractor_id
       and cc.start_date <= public.colombia_today()
       and (cc.end_date is null or cc.end_date >= public.colombia_today())
       and upper(cs.name) = 'PENDIENTE'
     order by cc.start_date desc, cc.id desc limit 1),
    'INACTIVO'::text
  );
$$;

create or replace function public.change_contractor_contract(
  p_contractor_id bigint,
  p_current_end_date date,
  p_new_start_date date,
  p_new_contract_type_id bigint
)
returns bigint
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
  actor uuid := auth.uid();
  today date := public.colombia_today();
  current_contract public.contractor_contract%rowtype;
  active_status_id bigint;
  inactive_status_id bigint;
  scheduled_status_id bigint;
  new_contract_id bigint;
  conflicting_operations text;
  draft record;
  eligible numeric;
  actor_name text;
begin
  if actor is null or not public.is_active_user()
    or not (public.has_role('COORDINATOR') or public.has_role('DIRECTOR')) then
    raise exception 'No autorizado';
  end if;
  if p_contractor_id is null or p_current_end_date is null
    or p_new_start_date is null or p_new_contract_type_id is null then
    raise exception 'Completa las fechas y el nuevo tipo de contrato';
  end if;

  perform 1 from public.contractor where id = p_contractor_id for update;
  if not found then raise exception 'Contratista no encontrado'; end if;
  select id into active_status_id from public.contract_status where upper(name) = 'ACTIVO';
  select id into inactive_status_id from public.contract_status where upper(name) = 'INACTIVO';
  select id into scheduled_status_id from public.contract_status where upper(name) = 'PROGRAMADO';
  if active_status_id is null or inactive_status_id is null or scheduled_status_id is null then
    raise exception 'Estados de contrato incompletos';
  end if;

  select cc.* into current_contract
  from public.contractor_contract cc
  where cc.contractor_id = p_contractor_id
    and cc.status_id = active_status_id
    and cc.start_date <= today
    and (cc.end_date is null or cc.end_date >= today)
  order by cc.start_date desc, cc.id desc limit 1 for update;
  if not found then raise exception 'El contratista no tiene un contrato activo vigente'; end if;
  if exists (select 1 from public.contractor_contract_transitions
             where contractor_id = p_contractor_id and status = 'SCHEDULED') then
    raise exception 'Ya existe un cambio de contrato programado';
  end if;
  if p_new_contract_type_id = current_contract.contract_type
    or not exists (select 1 from public.contract_type where id = p_new_contract_type_id) then
    raise exception 'Selecciona un tipo de contrato diferente y valido';
  end if;
  if p_current_end_date < current_contract.start_date or p_current_end_date > today then
    raise exception 'La fecha de fin debe estar entre el inicio del contrato actual y hoy';
  end if;
  if p_new_start_date < today or p_new_start_date <= p_current_end_date then
    raise exception 'El nuevo contrato debe iniciar hoy o despues y tras finalizar el actual';
  end if;

  select nullif(btrim(concat_ws(' ', name, last_name)), '') into actor_name
  from public.user_profiles where id = actor;
  actor_name := coalesce(actor_name, actor::text);

  select string_agg(format('#%s (%s)', o.id, to_char(o.operation_date, 'DD/MM/YYYY')),
                    ', ' order by o.operation_date, o.id)
  into conflicting_operations
  from (select distinct o.id, o.operation_date
        from public.operation_assignment oa
        join public.operation o on o.id = oa.operation_id
        where oa.contractor_id = p_contractor_id
          and oa.deleted_at is null
          and o.operation_date > p_current_end_date) o;
  if conflicting_operations is not null then
    raise exception 'No se puede cambiar el contrato. Tiene operaciones asignadas despues de la fecha de fin: %',
      conflicting_operations;
  end if;

  if exists (select 1 from public.contractor_payroll_periods
             where contractor_id = p_contractor_id and status = 'CLOSED'
               and period_end > p_current_end_date) then
    raise exception 'El cambio afecta nomina cerrada; solicita un ajuste administrativo';
  end if;

  update public.contractor_contract
  set end_date = p_current_end_date,
      status_id = case when p_current_end_date < today then inactive_status_id else active_status_id end,
      updated_at = public.colombia_now()
  where id = current_contract.id;

  insert into public.contractor_contract(
    contractor_id, contract_type, start_date, end_date, status_id, observations
  ) values (
    p_contractor_id, p_new_contract_type_id, p_new_start_date, null,
    case when p_new_start_date = today then active_status_id else scheduled_status_id end,
    format('Cambio de tipo desde el contrato #%s', current_contract.id)
  ) returning id into new_contract_id;

  insert into public.contractor_contract_transitions(
    contractor_id, old_contract_id, new_contract_id, old_end_date,
    new_start_date, status, created_by, created_by_name, completed_at
  ) values (
    p_contractor_id, current_contract.id, new_contract_id,
    p_current_end_date, p_new_start_date,
    case when p_new_start_date = today then 'COMPLETED' else 'SCHEDULED' end,
    actor, actor_name, case when p_new_start_date = today then public.colombia_now() else null end
  );

  -- Existing drafts are recalculated; closed payroll is never touched.
  for draft in
    select pp.* from public.contractor_payroll_periods pp
    where pp.contractor_id = p_contractor_id and pp.status = 'DRAFT'
    for update
  loop
    if draft.contractor_contract_id = current_contract.id then
      if draft.period_start > p_current_end_date then
        delete from public.contractor_payroll_periods where id = draft.id;
      else
        eligible := public.payroll_30_360_days(
          greatest(current_contract.start_date, draft.period_start),
          least(p_current_end_date, draft.period_end)
        );
        update public.contractor_payroll_periods
        set eligible_days = eligible,
            paid_days = least(paid_days, eligible),
            base_salary_amount = round(monthly_salary_snapshot * least(paid_days, eligible) / 30.0, 2),
            calculated_at = public.colombia_now(), updated_by = actor
        where id = draft.id;
      end if;
    end if;
  end loop;

  return new_contract_id;
end;
$$;

revoke all on function public.change_contractor_contract(bigint,date,date,bigint) from public, anon;
grant execute on function public.change_contractor_contract(bigint,date,date,bigint) to authenticated;

create or replace function public.process_scheduled_contractor_contracts()
returns void
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
  active_status_id bigint;
  inactive_status_id bigint;
  scheduled_status_id bigint;
begin
  select id into active_status_id from public.contract_status where upper(name) = 'ACTIVO';
  select id into inactive_status_id from public.contract_status where upper(name) = 'INACTIVO';
  select id into scheduled_status_id from public.contract_status where upper(name) = 'PROGRAMADO';

  update public.contractor_contract cc
  set status_id = inactive_status_id, updated_at = public.colombia_now()
  from public.contractor_contract_transitions t
  where t.old_contract_id = cc.id and t.status = 'SCHEDULED'
    and t.old_end_date < public.colombia_today() and cc.status_id = active_status_id;

  update public.contractor_contract cc
  set status_id = active_status_id, updated_at = public.colombia_now()
  from public.contractor_contract_transitions t
  where t.new_contract_id = cc.id and t.status = 'SCHEDULED'
    and t.new_start_date <= public.colombia_today() and cc.status_id = scheduled_status_id;

  update public.contractor_contract_transitions
  set status = 'COMPLETED', completed_at = public.colombia_now()
  where status = 'SCHEDULED' and new_start_date <= public.colombia_today();
end;
$$;

revoke all on function public.process_scheduled_contractor_contracts() from public, anon, authenticated;
select cron.schedule(
  'scheduled-contractor-contracts-colombia',
  '5 5 * * *',
  'select public.process_scheduled_contractor_contracts()'
);

create or replace function public.terminate_contractor(
  p_contractor_id bigint,
  p_termination_date date,
  p_reason_id bigint,
  p_observations text
)
returns void
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
  current_contract_id bigint;
  current_end_date date;
  inactive_status_id bigint;
  scheduled_transition public.contractor_contract_transitions%rowtype;
begin
  if auth.uid() is null or not public.is_active_user()
    or not (public.has_role('COORDINATOR') or public.has_role('DIRECTOR')) then
    raise exception 'No autorizado';
  end if;
  if p_contractor_id is null or p_termination_date is null or p_reason_id is null
    or nullif(btrim(p_observations), '') is null then
    raise exception 'Completa fecha, causa y observacion';
  end if;
  if not exists (select 1 from public.contractor_termination_reasons
                 where id = p_reason_id and is_active) then
    raise exception 'La causa de desvinculacion no es valida';
  end if;
  select id into inactive_status_id from public.contract_status where upper(name) = 'INACTIVO';
  if inactive_status_id is null then raise exception 'Falta el estado INACTIVO'; end if;

  perform 1 from public.contractor where id = p_contractor_id for update;
  if not found then raise exception 'Contratista no encontrado'; end if;
  if public.contractor_current_status(p_contractor_id) = 'INACTIVO' then
    raise exception 'El contratista ya se encuentra inactivo';
  end if;

  select cc.id, cc.end_date into current_contract_id, current_end_date
  from public.contractor_contract cc
  where cc.contractor_id = p_contractor_id and cc.start_date <= public.colombia_today()
    and (cc.end_date is null or cc.end_date >= public.colombia_today())
  order by cc.start_date desc, cc.id desc limit 1 for update;
  if current_contract_id is null then
    raise exception 'El contratista no tiene un contrato vigente';
  end if;
  if current_end_date is not null and p_termination_date > current_end_date then
    raise exception 'La desvinculacion no puede ser posterior al fin del contrato vigente';
  end if;

  select * into scheduled_transition
  from public.contractor_contract_transitions
  where contractor_id = p_contractor_id and status = 'SCHEDULED'
  for update;
  if found then
    if exists (select 1 from public.contractor_payroll_periods
               where contractor_contract_id = scheduled_transition.new_contract_id
                 and status = 'CLOSED') then
      raise exception 'No se puede cancelar un contrato programado con nomina cerrada';
    end if;
    delete from public.contractor_payroll_periods
    where contractor_contract_id = scheduled_transition.new_contract_id and status = 'DRAFT';
    update public.contractor_contract
    set status_id = inactive_status_id,
        observations = concat_ws(E'\n', observations, 'Contrato programado cancelado por desvinculacion'),
        updated_at = public.colombia_now()
    where id = scheduled_transition.new_contract_id;
    update public.contractor_contract_transitions
    set status = 'CANCELLED', cancelled_at = public.colombia_now(), cancelled_by = auth.uid()
    where id = scheduled_transition.id;
  end if;

  update public.contractor_contract
  set status_id = inactive_status_id,
      end_date = p_termination_date,
      termination_reason_id = p_reason_id,
      termination_observations = btrim(p_observations),
      terminated_by = auth.uid(),
      terminated_at = public.colombia_now(),
      updated_at = public.colombia_now(),
      observations = concat_ws(E'\n', observations, 'Desvinculado desde app movil')
  where id = current_contract_id;

  update public.contractor
  set termination_date = p_termination_date, disponibility = false,
      updated_at = public.colombia_now()
  where id = p_contractor_id;
end;
$$;

revoke all on function public.terminate_contractor(bigint,date,bigint,text) from public, anon;
grant execute on function public.terminate_contractor(bigint,date,bigint,text) to authenticated;

